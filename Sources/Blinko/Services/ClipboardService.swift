import AppKit
import Observation

struct ClipItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }
    let id = UUID()
    let content: Content
    let date: Date
    let sourceApp: String?

    var preview: String {
        switch content {
        case .text(let s): s.trimmingCharacters(in: .whitespacesAndNewlines)
        case .image: "Image"
        case .files(let urls): urls.map(\.lastPathComponent).joined(separator: ", ")
        }
    }
}

/// Clipboard history. macOS has no change notification, so this reads only the integer
/// `changeCount` once per second (timer with tolerance → coalesced wakeups) and copies
/// data only when it actually changed. Password-manager (concealed) entries are skipped.
@MainActor
@Observable
final class ClipboardService {
    static let shared = ClipboardService()

    private(set) var items: [ClipItem] = []

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var ignoreNextChange = false

    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    func refresh() {
        observeSystemState()
        Preferences.shared.clipboardHistory ? start() : stop()
    }

    private func start() {
        guard timer == nil, !isSuspended else { return }
        // Slower in Low Power Mode; tolerance lets macOS coalesce the wakeup with others.
        let interval: TimeInterval = ProcessInfo.processInfo.isLowPowerModeEnabled ? 3 : 1
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        t.tolerance = interval / 2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func stop() {
        pause()
        items.removeAll()
        lastChange = NSPasteboard.general.changeCount // re-enabling must not import old copies
    }

    private func pause() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Power gating
    //
    // Nobody copies while the display sleeps, the screen is locked or another user is active,
    // so the only periodic check in Blinko stops entirely then. A change made meanwhile is
    // still caught on resume (changeCount moved), it just isn't attributed to a source app.

    @ObservationIgnored private var observingSystem = false
    @ObservationIgnored private var displayAsleep = false
    @ObservationIgnored private var screenLocked = false
    @ObservationIgnored private var sessionInactive = false
    private var isSuspended: Bool { displayAsleep || screenLocked || sessionInactive }

    private func observeSystemState() {
        guard !observingSystem else { return }
        observingSystem = true
        let ws = NSWorkspace.shared.notificationCenter
        let dnc = DistributedNotificationCenter.default()
        let pairs: [(NotificationCenter, Notification.Name, ReferenceWritableKeyPath<ClipboardService, Bool>, Bool)] = [
            (ws, NSWorkspace.screensDidSleepNotification, \.displayAsleep, true),
            (ws, NSWorkspace.screensDidWakeNotification, \.displayAsleep, false),
            (ws, NSWorkspace.sessionDidResignActiveNotification, \.sessionInactive, true),
            (ws, NSWorkspace.sessionDidBecomeActiveNotification, \.sessionInactive, false),
            (dnc, Notification.Name("com.apple.screenIsLocked"), \.screenLocked, true),
            (dnc, Notification.Name("com.apple.screenIsUnlocked"), \.screenLocked, false),
        ]
        for (center, name, keyPath, value) in pairs {
            center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated {
                    guard let self else { return }
                    self[keyPath: keyPath] = value
                    self.applyGate()
                }
            }
        }
        NotificationCenter.default.addObserver(forName: .NSProcessInfoPowerStateDidChange, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self, self.timer != nil else { return }
                self.pause()
                self.start() // re-create with the new interval
            }
        }
    }

    private func applyGate() {
        guard Preferences.shared.clipboardHistory else { return }
        if isSuspended { pause() } else { start() }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ignoreNextChange { ignoreNextChange = false; return }

        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: Self.skipped) else { return }

        let content: ClipItem.Content
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(String(s.prefix(10_000)))
        } else if let image = NSImage(pasteboard: pb) {
            content = .image(image.downsampled(to: 320))
        } else {
            return
        }

        items.removeAll { $0.content == content }
        items.insert(ClipItem(content: content, date: .now,
                              sourceApp: NSWorkspace.shared.frontmostApplication?.localizedName), at: 0)
        let limit = max(5, Preferences.shared.clipboardLimit)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let i): pb.writeObjects([i])
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        ignoreNextChange = true
        // Move to top.
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }

    /// Design-time state for snapshot rendering.
    func injectPreview(_ texts: [(String, String)]) {
        items = texts.map { ClipItem(content: .text($0.0), date: .now, sourceApp: $0.1) }
    }
    func clear() { items.removeAll() }
}
