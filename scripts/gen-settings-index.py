#!/usr/bin/env python3
"""Generates Sources/Blinko/Views/Settings/SettingsSearchIndex.generated.swift.

Scans the Settings views for user-facing controls (Toggle, Picker, Stepper, Slider labels,
LabeledContent, Button, Section headers) and records which pane + section each lives in,
so Settings search never goes stale. Helper structs are attributed to the pane that uses
them. Run automatically by scripts/build.sh; safe to run by hand.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SETTINGS = ROOT / "Sources/Blinko/Views/Settings"
OUT = SETTINGS / "SettingsSearchIndex.generated.swift"

# Pane view struct → SettingsPane case. Add new panes here.
PANES = {
    "WelcomePane": "welcome", "GeneralPane": "general", "ActivitiesPane": "activities",
    "ModulesPane": "modules", "LayoutPane": "layout", "AppearancePane": "appearance",
    "MeetingsPane": "meetings", "CommandBarPane": "commandBar", "AboutPane": "about",
    "AgentsSettingsPane": "agents", "AutomationSettingsPane": "automation",
    "HomeLayoutPane": "homeLayout", "LockScreenPane": "lockScreen",
}

CONTROL = re.compile(r'\b(Toggle|Picker|Stepper|LabeledContent|Button|Section|Slider|PillButton)\(\s*"((?:[^"\\]|\\.)+)"')
STRUCT = re.compile(r'^\s*(?:private |fileprivate )?struct (\w+)\b[^{]*\{', re.M)

def structs_of(text):
    """Yields (name, body) for each top-level-ish struct by brace matching."""
    for m in STRUCT.finditer(text):
        i = m.end(); depth = 1
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0); i += 1
        yield m.group(1), text[m.end():i]

bodies = {}
for f in sorted(SETTINGS.glob("*.swift")):
    if f.name == OUT.name: continue
    for name, body in structs_of(f.read_text()):
        bodies.setdefault(name, body)

def owner_panes(name, seen=()):
    if name in PANES: return {PANES[name]}
    owners = set()
    for other, body in bodies.items():
        if other != name and other not in seen and re.search(rf'\b{name}\s*\(', body):
            owners |= owner_panes(other, seen + (name,))
    return owners

entries, skipped = [], []
for name, body in bodies.items():
    panes = owner_panes(name)
    if not panes:
        continue
    section = ""
    for m in CONTROL.finditer(body):
        kind, title = m.group(1), m.group(2)
        if "\\(" in title or len(title) < 2:  # interpolated / not searchable
            continue
        if kind == "Section":
            section = title
            continue
        for pane in sorted(panes):
            entries.append((title, pane, section))
for name in PANES:
    if name not in bodies: skipped.append(name)

seen, unique = set(), []
for e in entries:
    if (e[0], e[1]) not in seen:
        seen.add((e[0], e[1])); unique.append(e)

esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
lines = [
    "// Generated by scripts/gen-settings-index.py — do not edit by hand.",
    "",
    "extension SettingsSearch {",
    "    static let generatedEntries: [SettingsSearch.Entry] = [",
]
for title, pane, section in unique:
    lines.append(f'        .init(title: "{esc(title)}", pane: .{pane}, section: "{esc(section)}"),')
lines += ["    ]", "}", ""]
text = "\n".join(lines)
if not OUT.exists() or OUT.read_text() != text:
    OUT.write_text(text)
print(f"settings index: {len(unique)} entries", file=sys.stderr)
